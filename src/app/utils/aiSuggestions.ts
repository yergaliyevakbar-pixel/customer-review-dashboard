import { Review } from '../types';

export function generateAISuggestedResponse(review: Review): string {
  const { sentiment, rating, customerName, text, urgency } = review;

  // Extract key issues from the text (simple keyword matching for demo)
  const hasFood = /тамақ|еда|блюд|мясо|салат|плов|манты|бешбармак|куырдақ|лагман|бәліш|шұжық/i.test(text);
  const hasService = /қызмет|обслуживание|официант|персонал|менеджер|администратор|service/i.test(text);
  const hasWait = /күттік|ждали|баяу|медленн|долго|минут|час/i.test(text);
  const hasCold = /суық|холодн|остыл/i.test(text);
  const hasDirty = /лас|грязн|антисанитар/i.test(text);
  const hasExpensive = /қымбат|дорог|цен|бағалар/i.test(text);

  if (sentiment === 'positive' || rating >= 4) {
    return `Спасибо огромное за теплые слова, ${customerName.split(' ')[0]}! Мы очень рады, что вам понравилось у нас. Ваше мнение очень важно для нас. Будем рады видеть вас снова! 🙏`;
  }

  if (sentiment === 'neutral' || rating === 3) {
    return `Спасибо за ваш отзыв, ${customerName.split(' ')[0]}. Мы ценим вашу обратную связь и обязательно учтем ваши замечания для улучшения качества обслуживания. Надеемся, что в следующий раз сможем превзойти ваши ожидания! 😊`;
  }

  if (sentiment === 'uncertain') {
    return `Здравствуйте, ${customerName.split(' ')[0]}. Спасибо за ваш отзыв. Мы внимательно изучили ваши комментарии. Будем благодарны за возможность обсудить ваш опыт подробнее и улучшить качество нашего сервиса. Надеемся на вашу обратную связь.`;
  }

  // Negative sentiment - customize based on specific issues
  let response = `Здравствуйте, ${customerName.split(' ')[0]}. Приносим искренние извинения за негативный опыт. `;

  if (hasDirty) {
    response += 'Вопросы гигиены для нас крайне важны. Мы немедленно провели проверку и усилили контроль чистоты. ';
  } else if (hasCold) {
    response += 'Нам очень жаль, что блюда были поданы холодными. Мы провели беседу с кухней о соблюдении температурного режима. ';
  } else if (hasService) {
    response += 'Нам очень жаль, что уровень обслуживания вас разочаровал. Мы провели беседу с персоналом и работаем над улучшением качества сервиса. ';
  } else if (hasWait) {
    response += 'Приносим извинения за долгое ожидание. Мы оптимизируем процессы кухни, чтобы сократить время подачи. ';
  } else if (hasExpensive) {
    response += 'Благодарим за замечание о ценах. Мы стремимся предложить оптимальное соотношение цены и качества. ';
  } else if (hasFood) {
    response += 'Нам очень жаль, что качество блюд не оправдало ваших ожиданий. Мы передали ваши замечания шеф-повару. ';
  } else {
    response += 'Мы серьезно отнеслись к вашим замечаниям и принимаем меры для исправления ситуации. ';
  }

  if (urgency === 'high') {
    response += 'Мы хотели бы компенсировать ваш негативный опыт. Пожалуйста, свяжитесь с нами напрямую, чтобы мы могли все исправить. ';
  }

  response += 'Будем благодарны за возможность исправиться и показать лучшее качество нашего заведения. 🙏';

  return response;
}
